#!/usr/bin/env python3
"""Deploy Yet Another BINGO (MC 26.3 + Fabric) server on the ECS.

Idempotent config writer + systemd unit + daily backup timer.
Run ON the ECS via workbench exec. Does not download anything.
"""
import json
import os
import secrets
import stat
import sys

BASE = "/opt/bingo"
JAVA = None


def find_java():
    for name in sorted(os.listdir(BASE)):
        if name.startswith("jdk-25") and os.path.isdir(os.path.join(BASE, name)):
            p = os.path.join(BASE, name, "bin", "java")
            if os.access(p, os.X_OK):
                return p
    raise SystemExit("JDK 25 not found under /opt/bingo")


def write(path, content, mode=0o644):
    with open(path, "w", encoding="utf-8") as f:
        f.write(content)
    os.chmod(path, mode)


def main():
    java = find_java()
    print("JAVA=" + java)

    # --- eula ---
    write(os.path.join(BASE, "eula.txt"), "eula=true\n")

    # --- server.properties (preserve existing rcon password if present) ---
    props_path = os.path.join(BASE, "server.properties")
    existing = {}
    if os.path.exists(props_path):
        for line in open(props_path, encoding="utf-8"):
            if "=" in line and not line.startswith("#"):
                k, v = line.rstrip("\n").split("=", 1)
                existing[k] = v
    rcon_pw = existing.get("rcon.password") or secrets.token_hex(16)
    props = {
        "server-port": "25565",
        "query.port": "25565",
        "rcon.port": "25575",
        "enable-rcon": "true",
        "rcon.password": rcon_pw,
        "online-mode": "false",
        "white-list": "false",
        "enforce-whitelist": "false",
        "max-players": "10",
        "gamemode": "survival",
        "difficulty": "normal",
        "spawn-protection": "0",
        "view-distance": "10",
        "simulation-distance": "8",
        "motd": "BINGO 26.3 | Yet Another Bingo",
        "level-name": "world",
        "allow-flight": "true",
        "enable-command-block": "false",
        "broadcast-rcon-to-ops": "false",
        "sync-chunk-writes": "true",
        "network-compression-threshold": "256",
        "player-idle-timeout": "0",
        "op-permission-level": "4",
        "function-permission-level": "2",
    }
    lines = ["#Minecraft server properties", "#Generated by deploy_bingo_server.py"]
    lines += ["%s=%s" % (k, v) for k, v in sorted(props.items())]
    write(props_path, "\n".join(lines) + "\n", 0o600)
    print("server.properties written (rcon password preserved/created, not printed)")

    # --- empty ops / whitelist / banned lists ---
    for name in ("ops.json", "whitelist.json", "banned-players.json", "banned-ips.json"):
        p = os.path.join(BASE, name)
        if not os.path.exists(p):
            write(p, "[]\n")

    # --- systemd unit ---
    unit = """[Unit]
Description=Yet Another BINGO Minecraft 26.3 Fabric Server
After=network-online.target
Wants=network-online.target
Conflicts=mc.service lwi.service

[Service]
Type=simple
WorkingDirectory=/opt/bingo
ExecStart={java} -Xms2G -Xmx4G -XX:+UseZGC -XX:+ZGenerational -jar fabric-server-launch.jar nogui
Restart=on-failure
RestartSec=10
SuccessExitStatus=0 143
TimeoutStopSec=90
KillSignal=SIGTERM
StandardOutput=journal
StandardError=journal
LimitNOFILE=65536

[Install]
WantedBy=multi-user.target
""".format(java=java)
    write("/etc/systemd/system/bingo.service", unit)

    # --- backup script ---
    backup = """#!/bin/bash
# Daily cold-ish backup of BINGO server (save-off via RCON, tar, save-on).
set -eu
umask 077
BASE=/opt/bingo
DEST=/opt/backups
mkdir -p "$DEST"
STAMP=$(date +%Y%m%d-%H%M%S)
OUT="$DEST/bingo-$STAMP.tar.gz"
cd "$BASE"
PW=$(grep '^rcon.password=' server.properties | cut -d= -f2-)
PORT=$(grep '^rcon.port=' server.properties | cut -d= -f2-)
if systemctl is-active --quiet bingo.service; then
  python3 /opt/rcon.py 127.0.0.1 "$PORT" "$PW" "save-off" "save-all flush" >/dev/null || true
  sleep 3
fi
tar -C /opt -czf "$OUT" --exclude='bingo/jdk-25*' --exclude='bingo/jdk25.tar.gz' --exclude='bingo/logs' bingo
if systemctl is-active --quiet bingo.service; then
  python3 /opt/rcon.py 127.0.0.1 "$PORT" "$PW" "save-on" >/dev/null || true
fi
sha256sum "$OUT" > "$OUT.sha256"
# keep last 7
ls -1t "$DEST"/bingo-*.tar.gz 2>/dev/null | tail -n +8 | while read -r f; do rm -f -- "$f" "$f.sha256"; done
echo "BACKUP_OK $OUT"
"""
    write("/opt/bingo-backup.sh", backup, 0o700)

    bservice = """[Unit]
Description=BINGO server daily backup

[Service]
Type=oneshot
ExecStart=/opt/bingo-backup.sh
"""
    write("/etc/systemd/system/bingo-backup.service", bservice)
    btimer = """[Unit]
Description=BINGO server daily backup timer

[Timer]
OnCalendar=*-*-* 04:30:00
Persistent=true

[Install]
WantedBy=timers.target
"""
    write("/etc/systemd/system/bingo-backup.timer", btimer)

    print("units written")
    os.system("systemctl daemon-reload")
    print("DEPLOY_CONFIG_DONE")


if __name__ == "__main__":
    main()
